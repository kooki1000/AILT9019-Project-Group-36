"""Write docs/plan-data.js: the real sample run that the project page's board shows.

The page's interactive plan is not mocked up. This script runs the same code the app runs
(parser, difficulty score, planner) on data/samples/sample_requirements.txt with the bundled
demonstration reviews, and writes the result as a small JS file the page loads.

    python docs/build_plan_data.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from course_planner.difficulty import difficulty_score  # noqa: E402
from course_planner.metrics import load_variance  # noqa: E402
from course_planner.parser import parse_text  # noqa: E402
from course_planner.planner import PlanConstraints, generate_plan  # noqa: E402
from course_planner.reviews import load_dataset  # noqa: E402


def build(path: Path, with_reviews: bool) -> dict:
    parsed = parse_text(path.read_text(encoding="utf-8"))
    sentiments = load_dataset().sentiments if with_reviews else {}
    scores = {c.code: difficulty_score(c, sentiments.get(c.code, ())) for c in parsed.courses}
    difficulty = {code: s.score for code, s in scores.items()}
    constraints = PlanConstraints()
    result = generate_plan(parsed.courses, (), difficulty, constraints)
    return {
        "limits": {"credits": constraints.max_credits, "courses": constraints.max_courses},
        "courses": [
            {
                "code": c.code,
                "title": c.title,
                "credits": c.credits,
                "assessments": c.assessments,
                "prerequisites": [list(group) for group in c.prerequisites],
                "difficulty": difficulty[c.code],
                "reviews": scores[c.code].review_count,
            }
            for c in parsed.courses
        ],
        "plan": result.semesters,
        "baseline": result.baseline,
        "variance": {
            "plan": round(load_variance(result.semesters, difficulty), 2),
            "baseline": round(load_variance(result.baseline, difficulty), 2),
        },
    }


if __name__ == "__main__":
    sample = build(ROOT / "data" / "samples" / "sample_requirements.txt", with_reviews=True)
    # One of the five hand-built test documents (10 courses), scored from the document only,
    # exactly as `python -m course_planner.evaluation` does.
    case = ROOT / "tests" / "fixtures" / "requirements" / "case2_major_10_courses.txt"
    balance = build(case, with_reviews=False)
    out = ROOT / "docs" / "plan-data.js"
    out.write_text(
        "// Generated by docs/build_plan_data.py from real runs of the app's code. Do not edit.\n"
        "window.SAMPLE_RUN = " + json.dumps(sample, separators=(",", ":")) + ";\n"
        "window.BALANCE_RUN = " + json.dumps(balance, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {out.relative_to(ROOT)}")
